"""Issue random native unlock tokens without putting the bearer in build inputs.

The public directory and the private token file must be new, with separate,
existing, trusted parents. Only ship the public headers or resulting binary.
The token is a reusable bearer credential. This is not a password KDF, signed
license, anti-patching control, or guarantee of secrecy when a holder uses it.
"""

from __future__ import annotations

from contextlib import ExitStack
import hashlib
from importlib import resources
from pathlib import Path
import secrets
import unicodedata

from .core import GuardError, _root, safe_relative_path, write_new


NATIVE_TOKEN_PREFIX = "rg1_"
NATIVE_TOKEN_HEX_DIGITS = 64
_DOMAIN = b"OpenReleaseGuard/native-token/v1\x00"
_HELPER = "token_verify.hpp"


def _new_path(value: Path | str) -> Path:
    path = Path(value).absolute()
    safe_relative_path(path.name)
    path = _root(path.parent) / path.name
    try:
        path.lstat()  # Includes dangling links; never overwrite one.
    except FileNotFoundError:
        return path
    raise GuardError("Native token outputs must be new; existing files and directories are not replaced")


def _portable_parts(path: Path) -> tuple[str, ...]:
    return tuple(unicodedata.normalize("NFC", part).casefold() for part in path.parts)


def _public_header(digest: bytes) -> bytes:
    rows = [", ".join(f"0x{byte:02x}" for byte in digest[i:i + 8])
            for i in range(0, len(digest), 8)]
    return ("""// Generated by Release Guard. This digest may be public; keep the issued token private.
#pragma once
#include "releaseguard/token_verify.hpp"

namespace releaseguard {
inline constexpr native_token_digest issued_token_digest = {
    %s
};

inline bool verify_issued_token(std::string_view candidate) noexcept {
    return verify_native_token(candidate, issued_token_digest);
}
}  // namespace releaseguard
""" % ",\n    ".join(rows)).encode("ascii")


def issue_native_token(public_dir: Path | str, secret_out: Path | str) -> dict:
    """Create headers and write the sole issued bearer to a private file.

    Run outside a concurrently modified workspace. An ordinary failure rolls
    back only our own newly created outputs. Do not publish either result until
    success: there is no atomic commit across arbitrary filesystems.
    """
    public, secret = _new_path(public_dir), _new_path(secret_out)
    a, b = _portable_parts(public), _portable_parts(secret)
    if (a == b[:len(a)] or b == a[:len(b)] or a[:-1] == b[:-1]
            or public.parent.samefile(secret.parent)):
        raise GuardError("Put the native token outside the public output, in a separate private directory")

    helper = (resources.files("releaseguard") / "data" / "include" / "releaseguard" / _HELPER).read_bytes()
    token = (NATIVE_TOKEN_PREFIX + secrets.token_hex(NATIVE_TOKEN_HEX_DIGITS // 2)).encode("ascii")
    digest = hashlib.sha256(_DOMAIN + token).digest()
    header = public / "releaseguard_token.hpp"
    with ExitStack() as rollback:
        public.mkdir(mode=0o755)
        rollback.callback(public.rmdir)
        includes = public / "releaseguard"
        includes.mkdir(mode=0o755)
        rollback.callback(includes.rmdir)
        for path, data in ((includes / _HELPER, helper), (header, _public_header(digest))):
            write_new(path, data)
            rollback.callback(path.unlink)
        # No bearer is written to the public tree or returned in the report.
        write_new(secret, token + b"\n", secret=True)
        rollback.callback(secret.unlink)
        rollback.pop_all()
    return {
        "ok": True,
        "public_dir": str(public),
        "public_header": str(header),
        "secret_file": str(secret),
        "token_format": "rg1_ + 64 lowercase hexadecimal characters",
        "verifier_algorithm": "OpenReleaseGuard/native-token/v1 (SHA-256)",
    }
